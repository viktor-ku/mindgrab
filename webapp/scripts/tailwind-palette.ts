// Writes src/tailwind-palette.ts from the installed Tailwind's theme.css: each
// shade's color, and whether white or black text reads best on it. Run with
// `bun --bun run palette` after upgrading tailwindcss;
// tests/node-colors.test.ts fails until the file matches again.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

export type TextColor = "white" | "black";
export type Palette = Record<
  string,
  Record<string, { fill: string; text: TextColor }>
>;

// WCAG 2 relative luminance of an `oklch(L% C h)` color: OKLab to linear sRGB
// (clamped to the sRGB gamut), then the standard weights. Greys have no hue
// ("none").
export function luminance(oklch: string) {
  const match = /^oklch\(([\d.]+)% ([\d.]+) ([\d.]+|none)\)$/.exec(oklch);
  if (!match) throw new Error(`Not an oklch() color: ${oklch}`);
  const l = Number(match[1]) / 100;
  const c = Number(match[2]);
  const h = match[3] === "none" ? 0 : (Number(match[3]) * Math.PI) / 180;
  const a = c * Math.cos(h);
  const b = c * Math.sin(h);
  const lms = [
    l + 0.3963377774 * a + 0.2158037573 * b,
    l - 0.1055613458 * a - 0.0638541728 * b,
    l - 0.0894841775 * a - 1.291485548 * b,
  ].map((v) => v ** 3);
  const [r, g, bl] = [
    4.0767416621 * lms[0] - 3.3077115913 * lms[1] + 0.2309699292 * lms[2],
    -1.2684380046 * lms[0] + 2.6097574011 * lms[1] - 0.3413193965 * lms[2],
    -0.0041960863 * lms[0] - 0.7034186147 * lms[1] + 1.707614701 * lms[2],
  ].map((v) => Math.min(1, Math.max(0, v)));
  return 0.2126 * r + 0.7152 * g + 0.0722 * bl;
}

// The WCAG contrast ratio of two luminances, from 1 to 21.
export const contrast = (x: number, y: number) =>
  (Math.max(x, y) + 0.05) / (Math.min(x, y) + 0.05);

// Whichever of white and black contrasts more with the fill.
export function textFor(fill: string): TextColor {
  const y = luminance(fill);
  return contrast(y, 1) >= contrast(y, 0) ? "white" : "black";
}

export function readPalette(css: string): Palette {
  const palette: Palette = {};
  for (const [, family, shade, value] of css.matchAll(
    /--color-([a-z]+)-(\d+):\s*([^;]+);/g,
  )) {
    const fill = value.trim();
    palette[family] ??= {};
    palette[family][shade] = { fill, text: textFor(fill) };
  }
  return palette;
}

export function installedTheme() {
  const require = createRequire(import.meta.url);
  const path = require.resolve("tailwindcss/theme.css");
  const { version } = require("tailwindcss/package.json");
  return { css: readFileSync(path, "utf8"), version: version as string };
}

if (import.meta.main) {
  const { css, version } = installedTheme();
  const lines = [
    `// Generated by scripts/tailwind-palette.ts from tailwindcss ${version}. Do not edit.`,
    "// Each shade's color, and the text that reads best on it: white or black,",
    "// whichever has the higher WCAG contrast ratio.",
    "import type {",
    "  ColorFamily,",
    "  ColorShade,",
    '} from "./generated/mindgrab-state/model";',
    "",
    "export const TAILWIND_PALETTE = {",
  ];
  for (const [family, shades] of Object.entries(readPalette(css))) {
    lines.push(`  ${family}: {`);
    for (const [shade, { fill, text }] of Object.entries(shades))
      lines.push(`    ${shade}: { fill: "${fill}", text: "${text}" },`);
    lines.push("  },");
  }
  lines.push(
    "} as const satisfies Record<",
    "  ColorFamily,",
    '  Record<ColorShade, { fill: string; text: "white" | "black" }>',
    ">;",
    "",
  );
  const out = new URL("../src/tailwind-palette.ts", import.meta.url);
  writeFileSync(out, lines.join("\n"));
}
